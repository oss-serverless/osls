const crypto = require('crypto');
const fs = require('fs');
const fsp = require('fs').promises;
const path = require('path');
const { isDeepStrictEqual } = require('node:util');
const { pipeline } = require('node:stream/promises');
const { S3Client, GetObjectCommand } = require('@aws-sdk/client-s3');
const isObject = require('type/object/is');
const ServerlessError = require('../../../../serverless-error');
const deepSortObjectByKey = require('../../../../utils/deep-sort-object-by-key');
const { hasOwn, safeShallowAssign } = require('../../../../utils/safe-object');
const getHashForFilePath = require('../../../../utils/get-hash-for-file-path');
const resolveLambdaTarget = require('../../utils/resolve-lambda-target');
const parseS3URI = require('../../utils/parse-s3-uri');
const { log } = require('../../../../utils/serverless-utils/log');

const defaultCors = {
  allowedOrigins: ['*'],
  allowedHeaders: [
    'Content-Type',
    'X-Amz-Date',
    'Authorization',
    'X-Api-Key',
    'X-Amz-Security-Token',
    'X-Amzn-Trace-Id',
  ],
  allowedMethods: ['*'],
};
const runtimeManagementMap = new Map([
  ['auto', 'Auto'],
  ['onFunctionUpdate', 'FunctionUpdate'],
  ['manual', 'Manual'],
]);

const appendIfMissing = (items, item) => {
  if (!items.some((existingItem) => isDeepStrictEqual(existingItem, item))) {
    items.push(item);
  }
};

const uniq = (items) => Array.from(new Set(items));

const normalizeDependsOn = (items) => {
  const dependencies = uniq(items.filter(Boolean));
  if (!dependencies.length) return undefined;
  return dependencies.length === 1 ? dependencies[0] : dependencies;
};

const applyFunctionCondition = (resource, functionObject) => {
  if (functionObject.condition) {
    resource.Condition = functionObject.condition;
  }
  return resource;
};

const getTargetAliasLogicalId = (functionObject) =>
  functionObject.targetAlias && functionObject.targetAlias.logicalId;

